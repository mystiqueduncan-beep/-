"""Build/check the mobile homepage's ordered stylesheet bundle without changing CSS rules."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
NAMES = ["site.css","trend-marquee.css","mk-inspired.css","career-images.css","retro-editorial.css","pastel-details.css","view-mode-switch.css","research-cta.css","home-action-buttons.css"]
OUTPUT = ROOT / "assets/mobile-home.bundle.css"

# Preserve strings, escaped tokens and comment boundaries. Do not rewrite
# selectors, declaration values or rule order.
_TOKEN = re.compile(
    r"""/\*[\s\S]*?\*/|"(?:\\[\s\S]|[^"\\])*"|'(?:\\[\s\S]|[^'\\])*'|\\[0-9a-fA-F]{1,6}[\t\n\f\r ]*|\\[\s\S]|[\t\n\f\r ]+"""
)

def compact(source):
    def replace(match):
        token = match.group(0)
        if token.startswith("/*"):
            return token if token.startswith(("/*!", "/*#")) else "/**/"
        if re.fullmatch(r"[\t\n\f\r ]+", token):
            return " "
        return token
    return _TOKEN.sub(replace, source)

def build():
    parts = ["/* Generated by _qa/mobile_css_bundle.py. Edit source stylesheets, not this file. */\n"]
    for name in NAMES:
        source = (ROOT / "assets" / name).read_text(encoding="utf-8")
        if source.startswith("\ufeff") or re.search(r"@(?:import|charset|namespace)\b", source, re.I):
            raise ValueError(f"{name}: requires separate stylesheet or explicit rewriting")
        parts.append(f"\n/* Source: {name} */\n{compact(source.rstrip())}\n")
    return "".join(parts)

def check():
    expected = build()
    assert OUTPUT.read_text(encoding="utf-8") == expected, "Run python3 _qa/mobile_css_bundle.py to regenerate"
    html = (ROOT / "mobile.html").read_text(encoding="utf-8")
    assert html.count('href="assets/mobile-home.bundle.css"') == 1, "Mobile bundle must load exactly once"
    for name in NAMES:
        assert not re.search(r'href="assets/' + re.escape(name) + r'(?:\?[^"]*)?"', html), f"Duplicate stylesheet: {name}"

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    if parser.parse_args().check:
        check()
    else:
        OUTPUT.write_text(build(), encoding="utf-8")
        check()
